#!/usr/bin/env bash
# batch_p05_dual_instance_timing_fix.sh
#
# Fixes ONE real, VPS-observed failure from the first P0.5 delivery run:
# `dual_instance_chaos.test.js` ("(P0.5 dual-instance) ... only one holds
# the lease; kill it -> the other takes over after the TTL") timed out with
# "waitUntil timed out: initial lease acquisition by either instance" when
# run as part of the FULL test suite (103/104 passed; this was the only
# failure). Root cause: this test spawns two REAL OS child processes, and
# `node --test`'s default file-level concurrency runs several other
# CPU/timing-sensitive chaos-style test files at the same time - real CPU
# contention on the VPS pushed real child-process boot + lease acquisition
# past the original 5000ms margin. The lease/fencing mechanism itself was
# never in question: lease.test.js's 6 dedicated unit tests, and this exact
# test run in isolation, both passed cleanly before this fix. Full writeup:
# docs/P0_FINDINGS.md F9 (includes a reproduction under deliberately induced
# CPU contention, proving the new margin holds, not just a bigger number
# picked at random).
#
# This script only WRITES these 2 files and re-runs verification - it does
# NOT run `git add`/`git commit`.
#
# Run from the repository root: /home/sharwa/sharwa_ai
set -euo pipefail

REPO_ROOT="/home/sharwa/sharwa_ai"
if [ ! -d "$REPO_ROOT/gateway" ]; then
  echo "ERROR: $REPO_ROOT/gateway not found. Run this script from a machine where the repo lives at $REPO_ROOT, or edit REPO_ROOT at the top of this script." >&2
  exit 1
fi
cd "$REPO_ROOT"

echo "=== [0/4] Pre-flight: repo root = $REPO_ROOT ==="
git rev-parse --is-inside-work-tree >/dev/null 2>&1 && echo "  git repo: OK" || { echo "ERROR: not a git repository" >&2; exit 1; }

echo ""
echo "=== [1/4] Writing the 2 fixed files (base64-embedded, decoded in place) ==="

write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  cat > "$path.b64.tmp"
  base64 -d "$path.b64.tmp" > "$path"
  rm -f "$path.b64.tmp"
  echo "  wrote: $path ($(wc -c < "$path") bytes)"
}

