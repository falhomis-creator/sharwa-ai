echo ""
echo "=== [1/5] Writing fixed files (base64-embedded, decoded in place) ==="

write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  cat > "$path.b64.tmp"
  base64 -d "$path.b64.tmp" > "$path"
  rm -f "$path.b64.tmp"
  echo "  wrote: $path ($(wc -c < "$path") bytes)"
