#!/usr/bin/env bash
# batch_p06a_timing_fix2.sh
#
# Supersedes batch_p06a_timing_fix.sh's approach. That script's blanket
# `--test-concurrency=2` DID fix the two original failures (confirmed on your
# VPS: dual_instance_chaos.test.js passed), but the real full run it produced
# exposed two new problems, both real and both from your actual VPS output:
#   1. Total suite time exploded to ~24.6 minutes (was ~190s) - throttling
#      concurrency globally also slows down every fast, non-contentious test
#      file for no reason.
#   2. outbound_chaos.test.js (P0.4's own pre-existing chaos test, untouched
#      by any P0.6 change) FAILED for the first time ever - a real assertion
#      failure plus a "Promise resolution is still pending" warning - because
#      global concurrency=2 just redistributed the contention onto it
#      (paired against another heavy file instead of dozens of light ones).
#
# Full root-cause writeup and the corrected fix: docs/P0_FINDINGS.md F10
# (updated in place - the failed --test-concurrency=2 attempt is kept in the
# record, not erased, since it is itself a real finding).
#
# The actual fix: gateway/scripts/run-tests.sh (new) runs ONLY the three
# real-child-process-spawning files (dual_instance_chaos.test.js,
# outbound_chaos.test.js, p06_operational_readiness.test.js) sequentially
# among themselves (--test-concurrency=1), then runs every other file at
# node --test's normal, unrestricted default - those never contended with
# each other in the first place and lose nothing. gateway/package.json's
# "test" script now calls this file, so `npm test` and every delivery/CI
# script always match.
#
# Verified locally (not just claimed): 106/106 pass, ~43s total (both groups
# combined) - faster than the ORIGINAL default-concurrency run (~190s) and
# ~34x faster than the --test-concurrency=2 attempt (~1478s), with
# outbound_chaos.test.js passing cleanly with no "Promise pending" warning
# once isolated from the other two heavy files.
#
# This script only WRITES these 3 files and re-runs verification via the new
# canonical `npm test` (= gateway/scripts/run-tests.sh) - it does NOT run
# `git add`/`git commit`.
#
# Run from the repository root: /home/sharwa/sharwa_ai
set -euo pipefail

REPO_ROOT="/home/sharwa/sharwa_ai"
if [ ! -d "$REPO_ROOT/gateway" ]; then
  echo "ERROR: $REPO_ROOT/gateway not found. Run this script from a machine where the repo lives at $REPO_ROOT, or edit REPO_ROOT at the top of this script." >&2
  exit 1
fi
cd "$REPO_ROOT"

echo "=== [0/4] Pre-flight: repo root = $REPO_ROOT ==="
git rev-parse --is-inside-work-tree >/dev/null 2>&1 && echo "  git repo: OK" || { echo "ERROR: not a git repository" >&2; exit 1; }

echo ""
echo "=== [1/4] Writing the 3 fixed/new files (base64-embedded, decoded in place) ==="

write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  cat > "$path.b64.tmp"
  base64 -d "$path.b64.tmp" > "$path"
  rm -f "$path.b64.tmp"
  echo "  wrote: $path ($(wc -c < "$path") bytes)"
}

