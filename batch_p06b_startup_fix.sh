#!/usr/bin/env bash
# batch_p06b_startup_fix.sh
#
# Two REAL, MEASURED defects fixed (docs/P0_FINDINGS.md F13), plus two real
# test-harness defects fixed (F14). Nothing here is a guess.
#
# F13 - found by building a real TCP "black hole" (accepts the connection,
# never answers a byte - exactly what a wrong password / wrong service behind
# that host:port / hung Redis looks like to ioredis) and MEASURING a real
# gateway process:
#
#                              /healthz ready      SIGTERM exit
#   redis-cache healthy          1057ms  ->  758ms     13ms ->   16ms
#   redis-cache black hole      10698ms -> 2157ms    8475ms -> 1014ms
#   redis-cache ECONNREFUSED      717ms ->  681ms     19ms ->   12ms
#
#   1. main() awaited killSwitchRef.start(), which burned ioredis's
#      connectTimeout (5s) AND then commandTimeout (5s) on its first HGETALL -
#      making the kill-switch a STARTUP DEPENDENCY that delayed HTTP listen,
#      rehydrateSessions and every outbound worker by ~9.6s. The spec says
#      inbound/WAL is never gated on the kill-switch, and a kill-switch is an
#      enforcement layer, not a boot dependency. Now: the periodic timers are
#      armed BEFORE any await (so redis-cache recovering later is always
#      noticed), and the initial sync races a hard 1500ms cap, finishing in
#      the background if it overruns.
#   2. stop() closed both clients sequentially via quit(), which needs a
#      round-trip to a server that may never answer -> ~8.5s. That would have
#      blown p06_operational_readiness.test.js's own SHUTDOWN_TIMEOUT_MS=5000
#      budget and force-exited with code 1 instead of 0 - that test is exactly
#      the one that got cancelled by Ctrl+C on the VPS, so only an independent
#      measurement caught it. Now: both clients close in PARALLEL, each capped
#      at 1000ms, then disconnect() (local socket teardown, no round-trip).
#
# F14 - your outbound_chaos.test.js failure was NOT caused by Batch B: that
# test's child (_outbound_chaos_child.mjs) never calls main() and never builds
# a kill-switch at all (it passes ctx = { getSocket } only, so queue.js's
# check is the documented always-allow path), and outbound/queue.js does not
# even import killswitch.js. So REDIS_CACHE_HOST/PORT - the only delta
# between the passing and failing runs - cannot reach it. It also does not
# reproduce here: 3 clean runs 50/50 duplicates=0, plus one run under 3x CPU
# oversubscription, all passed. No timeout budget was touched (F10's lesson).
# What IS fixed are the two harness defects that made that failure useless:
#   1. The child's stdout was captured into an array that no assertion ever
#      read (dead capture), and stderr was piped but never drained (an unread
#      pipe can fill and BLOCK the child). Now every timing assertion carries
#      the child's real output, and stderr is drained.
#   2. The child was only killed on the happy path, so an assertion throwing
#      mid-round left it running - and a fork()'d child's live IPC channel
#      keeps the parent's event loop alive, so node:test printed the failure
#      and then HUNG (your 243s + Ctrl+C). A t.after() hook now kills it
#      whether the test passes or fails. Verified by forcing the round-0
#      assertion to fail: before = hung until killed at 90s, after = failed
#      and reported in 6s WITH the child's output attached.
#
# This script writes 3 files, then runs bounded diagnostics + tests. EVERY
# docker step is wrapped in `timeout` and the script never aborts on a failed
# step - you will get one complete report and will NOT need to Ctrl+C.
#
# Verified locally before sending: node --check on both JS files, hunt_gate
# greps clean, full suite 116/116 via the real `npm test`.
#
