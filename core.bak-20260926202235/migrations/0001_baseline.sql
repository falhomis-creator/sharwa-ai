-- Returns the governorate containing the point, or NULL if outside every known governorate
-- (=> reject candidate: sea, another country, hallucinated coordinate).
CREATE OR REPLACE FUNCTION app.point_governorate(p_lat double precision, p_lng double precision)
RETURNS bigint LANGUAGE sql STABLE AS $$
  SELECT id FROM geo_gazetteer
   WHERE level = 'governorate' AND ST_Covers(geom, ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326))
   LIMIT 1
$$;

