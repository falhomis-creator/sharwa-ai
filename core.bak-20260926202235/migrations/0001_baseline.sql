  RETURN v;
END $$;

-- =============================================================================
-- 8. Row Level Security on EVERY table that carries tenant_id (and is not a partition child)
--    Landmarks learned per tenant: tenant_id IS NULL rows are shared reference data.
-- =============================================================================

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = 'tenant_id' AND NOT a.attisdropped
     WHERE n.nspname = 'public' AND c.relkind IN ('r','p') AND NOT c.relispartition
       AND c.relname NOT IN ('geo_gazetteer')
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('CREATE POLICY tenant_isolation ON %I USING (tenant_id = app.current_tenant()) WITH CHECK (tenant_id = app.current_tenant())', r.relname);
  END LOOP;
END $$;

-- tenants has no tenant_id column (its id IS the tenant): a tenant-scoped session sees only itself.
ALTER TABLE tenants ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_self ON tenants USING (id = app.current_tenant());

-- kill_switches: tenant-scoped role sees global rows + its own tenant/channel rows; system role sees all.
ALTER TABLE kill_switches ENABLE ROW LEVEL SECURITY;
CREATE POLICY ks_app ON kill_switches FOR SELECT TO sharwa_app USING (
  scope = 'global'
  OR (scope = 'tenant' AND scope_id = app.current_tenant())
  OR (scope = 'channel_account' AND scope_id IN (SELECT id FROM channel_accounts))
);
CREATE POLICY ks_system ON kill_switches FOR SELECT TO sharwa_system USING (true);

ALTER TABLE geo_gazetteer ENABLE ROW LEVEL SECURITY;
CREATE POLICY gazetteer_read  ON geo_gazetteer FOR SELECT USING (tenant_id IS NULL OR tenant_id = app.current_tenant());
CREATE POLICY gazetteer_write ON geo_gazetteer FOR INSERT WITH CHECK (tenant_id = app.current_tenant());

-- =============================================================================
-- 9. Grants: least privilege. Partitions are NOT granted (only the parent), so RLS on the parent cannot be bypassed.
-- =============================================================================

GRANT USAGE ON SCHEMA public, app TO sharwa_app, sharwa_system;

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind IN ('r','p') AND NOT c.relispartition
  LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO sharwa_app', r.relname);
  END LOOP;
END $$;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sharwa_app;

