-- Hash-partitioned by tenant: a tenant's vectors live in one physical partition together with
-- other tenants' rows only by hash bucket; RLS + exact scan per tenant prevent any cross-tenant neighbour.
-- (Reference uses 8 partitions; production 32-64. Grants exist ONLY on the parent, never on partitions.)
