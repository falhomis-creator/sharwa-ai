-- Order-tracking identity rule (docs/01 §2.3): same WhatsApp number, OR order number + registered phone together.
-- Attempts are audited; the raw order number of a failed attempt is never stored (only its sha256).
CREATE TABLE order_lookup_attempts (
  id             bigserial PRIMARY KEY,
  tenant_id      uuid NOT NULL REFERENCES tenants(id),
  conversation_id uuid REFERENCES conversations(id),
  customer_id    uuid NOT NULL REFERENCES customers(id),
  path           text NOT NULL CHECK (path IN ('same_number','other_number')),
  order_ref_hash text NOT NULL,
  outcome        text NOT NULL CHECK (outcome IN ('allowed','denied','blocked')),
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX order_lookup_denied_customer_idx ON order_lookup_attempts (customer_id, created_at DESC) WHERE outcome = 'denied';
CREATE INDEX order_lookup_denied_order_idx    ON order_lookup_attempts (order_ref_hash, created_at DESC) WHERE outcome = 'denied';

-- Brute-force guard for the "other number" path (RLS scopes the counters to the current tenant):
--   * 3 denied attempts by the same customer identity within 24h  => path closed until the window clears
--   * 5 denied attempts on the same order (any identity) within 24h => that order can only be tracked via staff
CREATE OR REPLACE FUNCTION app.order_lookup_blocked(p_customer uuid, p_order_ref_hash text)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT (SELECT count(*) FROM order_lookup_attempts
           WHERE customer_id = p_customer AND path = 'other_number' AND outcome = 'denied'
             AND created_at > now() - interval '24 hours') >= 3
      OR (SELECT count(*) FROM order_lookup_attempts
           WHERE order_ref_hash = p_order_ref_hash AND outcome = 'denied'
             AND created_at > now() - interval '24 hours') >= 5
$$;

