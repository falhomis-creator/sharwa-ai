-- Cross-tenant claiming for system tasks: SECURITY DEFINER, the only surface sharwa_system may touch.
-- Stale bot replies (epoch changed / conversation no longer 'active') are dropped here, atomically.
CREATE OR REPLACE FUNCTION app.claim_outbox(p_limit integer, p_lease interval DEFAULT interval '60 seconds')
RETURNS SETOF outbox LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  UPDATE outbox o
     SET status = 'dropped_stale'
    FROM conversations c
   WHERE o.conversation_id = c.id
     AND o.status = 'pending' AND o.origin = 'bot'
     AND (c.epoch <> o.expected_epoch OR c.bot_status <> 'active');

  RETURN QUERY
  WITH picked AS (
    SELECT id FROM outbox
     WHERE (status = 'pending' AND next_attempt_at <= now())
        OR (status = 'sending' AND locked_until < now())     -- recover after a crashed dispatcher
     ORDER BY next_attempt_at
     FOR UPDATE SKIP LOCKED
     LIMIT p_limit
  )
  UPDATE outbox o
     SET status = 'sending', attempts = o.attempts + 1, locked_until = now() + p_lease
    FROM picked WHERE o.id = picked.id
  RETURNING o.*;
END $$;

CREATE OR REPLACE FUNCTION app.claim_due_jobs(p_limit integer, p_lease interval DEFAULT interval '120 seconds')
RETURNS SETOF scheduled_jobs LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
  WITH picked AS (
    SELECT id FROM scheduled_jobs
     WHERE (status = 'pending' AND run_at <= now())
        OR (status = 'processing' AND locked_until < now())
     ORDER BY run_at
     FOR UPDATE SKIP LOCKED
     LIMIT p_limit
  )
  UPDATE scheduled_jobs j
     SET status = 'processing', attempts = j.attempts + 1, locked_until = now() + p_lease
    FROM picked WHERE j.id = picked.id
  RETURNING j.*;
$$;

-- Resolve session -> tenant/channel BEFORE a tenant context exists (ingest). Returns nothing for unknown sessions.
CREATE OR REPLACE FUNCTION app.resolve_session(p_session_id text)
RETURNS TABLE (channel_account_id uuid, tenant_id uuid, engine text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT id, tenant_id, engine FROM channel_accounts WHERE session_id = p_session_id
$$;

