-- Allocate min(free units, waiters) holds to the OLDEST waiters, atomically.
-- The lock on stock_levels serializes concurrent allocations for the same variant, so
-- sum(active holds) can never exceed the observed available quantity - however many workers race.
-- (Postgres row locks, not Redis: a lost Redis lock cannot cause overselling.)
CREATE OR REPLACE FUNCTION app.allocate_stock_holds(p_variant text, p_available integer, p_ttl interval)
RETURNS SETOF stock_holds LANGUAGE plpgsql AS $$
DECLARE
  v_tenant uuid := app.current_tenant();
  v_active integer;
  v_free   integer;
BEGIN
  IF v_tenant IS NULL THEN RAISE EXCEPTION 'tenant context required'; END IF;
  IF p_available < 0 THEN RAISE EXCEPTION 'p_available must be >= 0'; END IF;

  INSERT INTO stock_levels (tenant_id, platform_variant_id, observed_available)
  VALUES (v_tenant, p_variant, p_available)
  ON CONFLICT (tenant_id, platform_variant_id) DO NOTHING;

  PERFORM 1 FROM stock_levels
   WHERE tenant_id = v_tenant AND platform_variant_id = p_variant FOR UPDATE;

  UPDATE stock_levels SET observed_available = p_available, observed_at = now()
   WHERE tenant_id = v_tenant AND platform_variant_id = p_variant;

  SELECT COALESCE(sum(qty), 0) INTO v_active FROM stock_holds
   WHERE tenant_id = v_tenant AND platform_variant_id = p_variant
     AND status = 'held' AND expires_at > now();

  v_free := GREATEST(p_available - v_active, 0);
  IF v_free = 0 THEN RETURN; END IF;

  RETURN QUERY
  WITH picked AS (
    SELECT id FROM waitlist_entries
     WHERE tenant_id = v_tenant AND platform_variant_id = p_variant AND status = 'waiting'
     ORDER BY created_at, id
     FOR UPDATE SKIP LOCKED
     LIMIT v_free
  ), upd AS (
    UPDATE waitlist_entries w SET status = 'held' FROM picked WHERE w.id = picked.id RETURNING w.id
  )
  INSERT INTO stock_holds (tenant_id, waitlist_entry_id, platform_variant_id, qty, expires_at)
  SELECT v_tenant, upd.id, p_variant, 1, now() + p_ttl FROM upd
  RETURNING *;
END $$;

-- Expire overdue holds; the caller then re-runs allocate_stock_holds so the next in line is promoted.
CREATE OR REPLACE FUNCTION app.expire_stock_holds(p_variant text)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE v_n integer;
BEGIN
  IF app.current_tenant() IS NULL THEN RAISE EXCEPTION 'tenant context required'; END IF;
  WITH e AS (
    UPDATE stock_holds SET status = 'expired'
     WHERE tenant_id = app.current_tenant() AND platform_variant_id = p_variant
       AND status = 'held' AND expires_at <= now()
    RETURNING waitlist_entry_id
  )
  UPDATE waitlist_entries w SET status = 'expired' FROM e WHERE w.id = e.waitlist_entry_id;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END $$;

