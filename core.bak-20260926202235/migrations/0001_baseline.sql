-- Assign messages.seq atomically per conversation, keep the conversation counters in step.
-- The UPDATE takes a row lock on the conversation, which serializes concurrent inserts.
CREATE OR REPLACE FUNCTION app.trg_messages_seq() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_seq bigint;
BEGIN
  UPDATE conversations
     SET message_seq      = message_seq + 1,
         last_inbound_seq = CASE WHEN NEW.direction = 'in' THEN message_seq + 1 ELSE last_inbound_seq END,
         needs_turn       = CASE WHEN NEW.direction = 'in' AND bot_status = 'active' THEN true ELSE needs_turn END,
         last_message_at  = now()
   WHERE id = NEW.conversation_id AND tenant_id = NEW.tenant_id
   RETURNING message_seq INTO v_seq;
  IF v_seq IS NULL THEN
    RAISE EXCEPTION 'conversation % not found for tenant %', NEW.conversation_id, NEW.tenant_id;
  END IF;
  NEW.seq := v_seq;
  -- A human outbound message pauses the bot IN THE SAME TRANSACTION (risk #11).
  IF NEW.direction = 'out' AND NEW.sent_by = 'staff' THEN
    UPDATE conversations
       SET bot_status = 'paused_human', epoch = epoch + 1, version = version + 1,
           handoff_reason = COALESCE(handoff_reason, 'staff_replied')
     WHERE id = NEW.conversation_id AND bot_status = 'active';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER messages_seq BEFORE INSERT ON messages
  FOR EACH ROW EXECUTE FUNCTION app.trg_messages_seq();

-- The ONLY way to change bot_status (column-level grants below forbid direct UPDATE). Optimistic lock.
-- Returns the new epoch, or NULL when the version is stale (caller re-reads and decides).
CREATE OR REPLACE FUNCTION app.set_bot_status(p_conv uuid, p_expected_version integer, p_new_status text,
                                              p_reason text, p_staff uuid DEFAULT NULL)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_epoch integer;
BEGIN
  IF app.current_tenant() IS NULL THEN
    RAISE EXCEPTION 'tenant context required';
  END IF;
  IF p_new_status NOT IN ('active','paused_human','closed') THEN
    RAISE EXCEPTION 'invalid bot_status %', p_new_status;
  END IF;
  UPDATE conversations
     SET bot_status = p_new_status, epoch = epoch + 1, version = version + 1,
         handoff_reason = p_reason, assigned_staff_id = COALESCE(p_staff, assigned_staff_id),
         needs_turn = CASE WHEN p_new_status = 'active' THEN needs_turn ELSE false END
   WHERE id = p_conv AND tenant_id = app.current_tenant() AND version = p_expected_version
   RETURNING epoch INTO v_epoch;
  RETURN v_epoch;   -- NULL => stale version or not this tenant's conversation
END $$;

