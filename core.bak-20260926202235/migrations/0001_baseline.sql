-- Kill switches (risk #19). Global rows have NULL scope_id. No RLS: managed by admin API only.
CREATE TABLE kill_switches (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  scope      text NOT NULL CHECK (scope IN ('global','tenant','channel_account')),
  scope_id   uuid,
  capability text NOT NULL CHECK (capability IN
             ('*','ai_reply','marketing','broadcast','geocode_auto','gift','fit','checkout','back_in_stock','media')),
  state      text NOT NULL CHECK (state IN ('on','degraded','off')),
  reason     text,
  set_by     text NOT NULL,
  set_at     timestamptz NOT NULL DEFAULT now(),
  CHECK ((scope = 'global') = (scope_id IS NULL)),
  UNIQUE NULLS NOT DISTINCT (scope, scope_id, capability)
);

-- Most restrictive of (global, tenant, channel) x (capability, '*') wins: off > degraded > on.
CREATE OR REPLACE FUNCTION app.effective_switch(p_tenant uuid, p_channel uuid, p_capability text)
RETURNS text LANGUAGE sql STABLE AS $$
  SELECT COALESCE(
    (SELECT CASE max(CASE state WHEN 'off' THEN 2 WHEN 'degraded' THEN 1 ELSE 0 END)
              WHEN 2 THEN 'off' WHEN 1 THEN 'degraded' ELSE 'on' END
       FROM kill_switches
      WHERE capability IN (p_capability, '*')
        AND ( scope = 'global'
           OR (scope = 'tenant' AND scope_id = p_tenant)
           OR (scope = 'channel_account' AND scope_id = p_channel) )),
    'on')
$$;

