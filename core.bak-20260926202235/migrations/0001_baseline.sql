-- =============================================================================
-- Sharwa AI - reference database schema (PostgreSQL 16 + pgvector + PostGIS)
--
-- Purpose: make the architecture's hard guarantees enforceable IN THE DATABASE,
-- so they hold even if application code has a bug:
--   #1  cross-tenant isolation      -> RLS on every tenant table + hash-partitioned vectors
--   #5  idempotency                 -> UNIQUE constraints (inbound_events, outbox, scheduled_jobs)
--   #7  back-in-stock race          -> app.allocate_stock_holds() (row locks, no Redis locks)
--   #11 handoff state machine       -> bot_status/epoch/version writable ONLY via app.handoff_*()
--   #17 durable queues              -> outbox / scheduled_jobs / campaign_recipients + claim functions
--   #20 money                       -> BIGINT minor units + ISO currency, never float
--
-- Roles (created NOLOGIN here; deployment creates LOGIN roles that inherit):
--   sharwa_app     tenant-scoped application role. NOT the table owner => subject to RLS.
--   sharwa_system  cross-tenant system tasks (dispatcher/sweeper/ingest). May ONLY execute the
--                  SECURITY DEFINER functions granted below; has no direct table access.
--
-- Every tenant-scoped transaction MUST begin with:  SET LOCAL app.tenant_id = '<uuid>';
-- (transaction-scoped => safe behind PgBouncer in transaction-pooling mode)
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS postgis;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sharwa_app') THEN
    CREATE ROLE sharwa_app NOLOGIN NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sharwa_system') THEN
    CREATE ROLE sharwa_system NOLOGIN NOBYPASSRLS;
  END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS app;

-- Tenant context helper. Missing/empty setting => NULL => every RLS predicate is NULL => zero rows.
CREATE OR REPLACE FUNCTION app.current_tenant() RETURNS uuid
LANGUAGE sql STABLE AS
$$ SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid $$;

