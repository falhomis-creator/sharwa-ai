#!/usr/bin/env bash
# batch_p06a_timing_fix.sh
#
# Fixes ONE real, VPS-observed failure pair from the first P0.6 Batch A run
# (batch_p06a_operational_readiness.sh): both dual_instance_chaos.test.js AND
# the new p06_operational_readiness.test.js's real-process test timed out
# together under the full suite's real CPU contention - the same class of
# flakiness as P0.5's own F9, now recurring because this batch added more
# real-child-process-spawning tests than `node --test`'s own CPU-aware
# scheduling accounts for. Full root-cause writeup: docs/P0_FINDINGS.md F10.
#
# Fix is two-layered:
#   1) Root cause: cap `--test-concurrency=2` in the suite's own run command
#      below (this script's own [3/4] step, and the one to reuse in any
#      future manual run) - fewer test FILES run in parallel, so the real OS
#      processes those files spawn internally no longer pile up beyond what
#      the machine can actually run concurrently.
#   2) Second line of defense: both timing-sensitive tests' own margins
#      widened further (not the primary fix - see F10 for why an
#      ever-growing timeout alone is not sustainable).
#
# This script only WRITES these 3 files and re-runs verification - it does
# NOT run `git add`/`git commit`.
#
# Run from the repository root: /home/sharwa/sharwa_ai
set -euo pipefail

REPO_ROOT="/home/sharwa/sharwa_ai"
if [ ! -d "$REPO_ROOT/gateway" ]; then
  echo "ERROR: $REPO_ROOT/gateway not found. Run this script from a machine where the repo lives at $REPO_ROOT, or edit REPO_ROOT at the top of this script." >&2
  exit 1
fi
cd "$REPO_ROOT"

echo "=== [0/4] Pre-flight: repo root = $REPO_ROOT ==="
git rev-parse --is-inside-work-tree >/dev/null 2>&1 && echo "  git repo: OK" || { echo "ERROR: not a git repository" >&2; exit 1; }

echo ""
echo "=== [1/4] Writing the 3 fixed files (base64-embedded, decoded in place) ==="

write_file() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  cat > "$path.b64.tmp"
  base64 -d "$path.b64.tmp" > "$path"
  rm -f "$path.b64.tmp"
  echo "  wrote: $path ($(wc -c < "$path") bytes)"
}

